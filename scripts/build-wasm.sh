#!/usr/bin/env sh
# Builds crates/airband-wasm and writes the browser module to
# frontend/src/generated/wasm (committed, so building the frontend never
# needs a Rust toolchain). Requires: rustup target add wasm32-unknown-unknown,
# and wasm-bindgen-cli at the same version as the crate's wasm-bindgen
# (cargo install wasm-bindgen-cli --version 0.2.129 --locked).
set -eu
cd "$(dirname "$0")/.."
cargo build --release --target wasm32-unknown-unknown -p airband-wasm
wasm-bindgen --target web --no-typescript --out-dir frontend/src/generated/wasm \
  target/wasm32-unknown-unknown/release/airband_wasm.wasm
cat > frontend/src/generated/wasm/airband_wasm.d.ts <<'DTS'
// Generated by scripts/build-wasm.sh. Do not edit this file manually.
export default function init(input?: unknown): Promise<unknown>;
export function validate(config_json: string): string;
export function validate_for(config_json: string, features_json: string): string;
DTS
ls -l frontend/src/generated/wasm
